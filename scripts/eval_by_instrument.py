"""Per-instrument-class re-scoring of an EXISTING eval output tree.

Reuses the audio already generated by gen_and_evaluate.py (no new
generation): every per-sample dir under the eval root carries the
precompute's metadata.json with `target_inst_id`, so samples are
grouped by the held-out target stem's instrument class, a symlink
farm is built per group, and the SAME three metric helpers used by
gen_and_evaluate.py are run on each group root — the protocol is
therefore identical to the headline eval, just restricted per group.

Requires the eval root to still contain the audio (i.e. a run made
WITHOUT --remove_generation) including the *_16000.wav resamples.

FAD caveat: it is a set-level metric; treat groups with small n
(< ~50) as indicative only. Per-group n is written into the JSON.

Group spec: JSON mapping group name -> list of inst-class ids, e.g.
  {"drums": [14], "bass": [4], "guitar": [3], "keys": [0, 1, 2]}
Ids follow stream_music_gen.constants.MIDI_CATEGORIES order.
"""

import argparse
import json
import os
import shutil

import numpy as np

import stream_music_gen.eval.cocola_eval as cocola_eval
import stream_music_gen.eval.fad_eval as fad_eval
from stream_music_gen.eval.beat_alignment_eval import beat_alignment_score
from stream_music_gen.constants import MIDI_CATEGORIES, EVAL_SAMPLE_RATE

F_MEASURE_KEY = "madmom_fmeasure"
COCOLA_MODES = ["both", "harmonic", "percussive"]


def mean_std(values):
    return {"mean": float(np.mean(values)), "std": float(np.std(values))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--eval_root",
        required=True,
        help="existing eval dir containing per-sample subdirs (00000/...)",
    )
    parser.add_argument(
        "--groups",
        default=None,
        help='JSON string: {"group_name": [inst_class_id, ...], ...}',
    )
    parser.add_argument(
        "--groups_file",
        default=None,
        help="path to a JSON file with the same structure as --groups",
    )
    parser.add_argument("--results_tag", required=True)
    parser.add_argument("--results_save_dir", default="logs/eval_results")
    parser.add_argument("--skip_fad", action="store_true", default=False)
    args = parser.parse_args()

    if args.groups is not None:
        groups = json.loads(args.groups)
    elif args.groups_file is not None:
        with open(args.groups_file) as f:
            groups = json.load(f)
    else:
        raise SystemExit("one of --groups / --groups_file is required")

    eval_root = os.path.abspath(args.eval_root)
    inst_names = [category[0] for category in MIDI_CATEGORIES]

    sample_dirs = sorted(
        d
        for d in os.listdir(eval_root)
        if d.isdigit() and os.path.isdir(os.path.join(eval_root, d))
    )
    if not sample_dirs:
        raise SystemExit(f"no per-sample dirs under {eval_root}")

    by_group = {name: [] for name in groups}
    inst_id_counts = {}
    for d in sample_dirs:
        with open(os.path.join(eval_root, d, "metadata.json")) as f:
            inst_id = int(json.load(f)["target_inst_id"])
        inst_id_counts[inst_id] = inst_id_counts.get(inst_id, 0) + 1
        for name, ids in groups.items():
            if inst_id in ids:
                by_group[name].append(d)

    farm_root = eval_root.rstrip("/") + "_by_inst"
    results = {
        "eval_root": eval_root,
        "num_samples_total": len(sample_dirs),
        "target_inst_id_counts": {
            f"{i} ({inst_names[i]})": n
            for i, n in sorted(inst_id_counts.items())
        },
        "groups": {},
    }

    for name, ids in groups.items():
        dirs = by_group[name]
        group_result = {
            "inst_ids": ids,
            "inst_names": [inst_names[i] for i in ids],
            "n": len(dirs),
        }
        results["groups"][name] = group_result
        if not dirs:
            print(f"[{name}] 0 samples — skipping")
            continue

        group_root = os.path.join(farm_root, name)
        if os.path.isdir(group_root):
            shutil.rmtree(group_root)
        os.makedirs(group_root)
        for d in dirs:
            os.symlink(
                os.path.join(eval_root, d), os.path.join(group_root, d)
            )
        print(f"[{name}] {len(dirs)} samples (inst_ids={ids})")

        gt_beat, pred_beat = beat_alignment_score(
            group_root,
            context_path="input_audio.wav",
            gt_path="ground_truth/pred.wav",
            pred_path="pred/pred.wav",
        )
        group_result["beat_alignment"] = {
            "gt_f_measure": mean_std(gt_beat[F_MEASURE_KEY]),
            "pred_f_measure": mean_std(pred_beat[F_MEASURE_KEY]),
        }
        print(
            f"[{name}] Beat-F pred "
            f"{group_result['beat_alignment']['pred_f_measure']['mean']:.4f}"
        )

        gt_cocola, pred_cocola = cocola_eval.cocola_score(
            group_root,
            context_path=f"input_audio_{EVAL_SAMPLE_RATE}.wav",
            gt_path=f"ground_truth/pred_{EVAL_SAMPLE_RATE}.wav",
            pred_path=f"pred/pred_{EVAL_SAMPLE_RATE}.wav",
            embedding_modes=COCOLA_MODES,
        )
        group_result["cocola"] = {
            mode: {
                "gt_scores": mean_std(gt_cocola[mode]),
                "pred_scores": mean_std(pred_cocola[mode]),
            }
            for mode in COCOLA_MODES
        }
        print(
            f"[{name}] CoCoLa(both) pred "
            f"{group_result['cocola']['both']['pred_scores']['mean']:.2f}"
        )

        if not args.skip_fad:
            fad_score = fad_eval.calculate_fad(
                group_root,
                gt_path=f"ground_truth/pred_{EVAL_SAMPLE_RATE}.wav",
                gen_path=f"pred/pred_{EVAL_SAMPLE_RATE}.wav",
                metric="vggish",
                verbose=False,
            )
            group_result["fad"] = {"score": float(fad_score)}
            print(f"[{name}] FAD {fad_score:.3f} (n={len(dirs)})")

    os.makedirs(args.results_save_dir, exist_ok=True)
    results_file = os.path.join(
        args.results_save_dir, args.results_tag + ".json"
    )
    with open(results_file, "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nResults saved to: {results_file}")


if __name__ == "__main__":
    main()
